import UIKit

enum AppColor {
    static let background = UIColor.systemBackground
    static let groupedBackground = UIColor.systemGroupedBackground
    static let surface = UIColor.secondarySystemGroupedBackground
    static let elevatedSurface = UIColor.tertiarySystemGroupedBackground
    static let textPrimary = UIColor.label
    static let textSecondary = UIColor.secondaryLabel
    static let textInverse = UIColor.white
    static let border = UIColor.separator
    static let accent = UIColor.systemBlue
    static let accentSecondary = UIColor.systemIndigo
    static let success = UIColor.systemGreen
    static let warning = UIColor.systemOrange
    static let error = UIColor.systemRed
}
